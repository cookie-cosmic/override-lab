// Markdown report generation — the deliverable a coach actually takes away.
import { round } from '../util.js'

const row = (cells) => `| ${cells.map((c) => (c == null ? '—' : c)).join(' | ')} |`
const pct = (v) => (v == null ? '—' : `${Math.round(v * 100)}%`)

export function eventReport({ event, summary, meta }) {
  const s = summary
  const L = []
  L.push(`# ${event.name}`)
  L.push('')
  L.push(`_${event.program || 'VRC'} · ${event.season || 'season n/a'} · ${event.start_date || 'date n/a'}_`)
  L.push('')
  L.push(`- Teams: **${s.count.teams}**`)
  L.push(`- Matches: **${s.count.matches}** (${s.count.scored} scored)`)
  L.push(`- Median winning margin: **${s.distributions.medianMargin}** points`)
  L.push(`- Matches inside 5 points: **${s.distributions.close}** · decided by 25+: **${s.distributions.blowouts}**`)
  if (s.bracket.champion) L.push(`- Champion: **${s.bracket.champion.join(' + ')}**`)
  L.push('')

  if (s.digest) {
    L.push('## What happened')
    L.push('')
    for (const p of s.digest.paragraphs) L.push(p, '')
    if (s.digest.claims?.length) {
      L.push('**Evidence**')
      L.push('')
      for (const c of s.digest.claims) L.push(`- ${c.text} _(confidence: ${c.confidence})_`)
      L.push('')
    }
  }

  L.push('## Power ranking (Elo with bootstrap band)')
  L.push('')
  L.push(row(['#', 'Team', 'Elo', '80% band', 'Avg pts', 'WAE', 'Seed']))
  L.push(row(['---', '---', '---', '---', '---', '---', '---']))
  s.leaderboards.power.forEach((t, i) => {
    L.push(row([i + 1, t.team, t.elo, `${t.band?.[0]}–${t.band?.[1]}`, t.avgPoints, t.winsAboveExpectation, t.rank]))
  })
  L.push('')

  L.push('## Biggest upsets (by pre-match win probability)')
  L.push('')
  if (!s.upsets.length) L.push('_No matches finished below a 40% pre-match win probability._')
  else {
    L.push(row(['Round', 'Winner', 'Score', 'Winner P(win)']))
    L.push(row(['---', '---', '---', '---']))
    for (const u of s.upsets) L.push(row([u.roundLabel, (u.winner === 'red' ? u.red : u.blue).join(' + '), `${u.redScore}–${u.blueScore}`, pct(u.winnerP)]))
  }
  L.push('')

  if (s.leaderboards.penalties?.length) {
    L.push('## Penalty pressure')
    L.push('')
    L.push(row(['Team', 'Penalty pts / match']))
    L.push(row(['---', '---']))
    for (const p of s.leaderboards.penalties) L.push(row([p.team, p.value]))
    L.push('')
  }

  if (meta?.correlations?.length) {
    L.push('## What actually predicts winning here')
    L.push('')
    L.push(row(['Relationship', 'r', 'n']))
    L.push(row(['---', '---', '---']))
    for (const c of meta.correlations) L.push(row([c.label, c.r, c.n]))
    L.push('')
    L.push('_Correlation across teams at this event, not a causal claim. With this sample size, |r| below ~0.3 is noise._')
    L.push('')
  }

  if (meta?.archetypePerformance?.length) {
    L.push('## Archetypes')
    L.push('')
    L.push(row(['Archetype', 'Teams', 'Avg pts', 'Win rate', 'Avg Elo']))
    L.push(row(['---', '---', '---', '---', '---']))
    for (const a of meta.archetypePerformance) L.push(row([a.label, a.size, a.avgPoints, pct(a.winRate), a.avgElo]))
    L.push('')
  }

  if (s.model?.calibration?.brier != null) {
    const c = s.model.calibration
    L.push('## Model honesty')
    L.push('')
    L.push(`Pre-match model: Brier **${c.brier}** vs **${c.baselineBrier}** for a constant 50% guess, log loss ${c.logLoss}, n=${c.n} (${c.method}).`)
    L.push('')
  }

  if (s.quality) {
    L.push('## Data quality')
    L.push('')
    L.push(row(['Check', 'Value']))
    L.push(row(['---', '---']))
    L.push(row(['Scored matches', s.quality.scored]))
    L.push(row(['With phase breakdown (auto/driver/penalty)', s.quality.breakdownAvailable]))
    L.push(row(['Missing scheduled times', s.quality.missingSchedule]))
    L.push(row(['Videos linked', s.quality.videos]))
    L.push(row(['Matches aligned to video', s.quality.aligned]))
    L.push(row(['Matches with tagged score timeline', s.quality.tagged]))
    L.push(row(['Teams with scouting notes', s.quality.scouting]))
    L.push('')
    if (s.quality.breakdownAvailable === 0) {
      L.push('_No phase breakdown in this source: autonomous / driver-control splits and the in-game win-probability curve are unavailable until either a RobotEvents token is used or a match timeline is tagged against video._')
      L.push('')
    }
  }

  L.push('---')
  L.push('_Generated by Override Lab. Ratings are event-local; claims are model-conditional._')
  return L.join('\n')
}

export function teamReport({ teamView, event }) {
  const { team: t, briefing, prescription, style, percentiles } = teamView
  const L = []
  L.push(`# ${t.team}${t.name ? ` — ${t.name}` : ''}`)
  L.push('')
  L.push(`_${event.name} · ${event.season || ''}_`)
  L.push('')
  L.push('## Snapshot')
  L.push('')
  L.push(row(['Metric', 'Value']))
  L.push(row(['---', '---']))
  L.push(row(['Archetype', style?.archetype || '—']))
  L.push(row(['Record', `${t.wins}–${t.losses}${t.ties ? `–${t.ties}` : ''} in ${t.matches}`]))
  L.push(row(['Seed / rank', t.rank ?? '—']))
  L.push(row(['Elo', `${t.elo} (80% band ${t.eloBand?.[0]}–${t.eloBand?.[1]})`]))
  L.push(row(['OPR', t.opr]))
  L.push(row(['Average points', t.avgPoints]))
  L.push(row(['Floor / ceiling', `${t.floor} / ${t.ceiling}`]))
  L.push(row(['Wins above expectation', t.winsAboveExpectation]))
  L.push(row(['Autonomous pts / match', t.autonPerMatch ?? '—']))
  L.push(row(['Driver pts / match', t.driverPerMatch ?? '—']))
  L.push(row(['Penalties / match', t.penaltyPerMatch ?? '—']))
  L.push(row(['Skills (driver / prog)', `${t.skills?.driver ?? '—'} / ${t.skills?.prog ?? '—'}`]))
  L.push('')

  if (briefing) {
    L.push('## Read')
    L.push('')
    for (const p of briefing.paragraphs) L.push(p, '')
    if (briefing.claims?.length) {
      L.push('**Evidence**')
      L.push('')
      for (const c of briefing.claims) L.push(`- ${c.text} _(confidence: ${c.confidence})_`)
      L.push('')
    }
  }

  if (prescription?.dims?.length) {
    L.push('## Practice priorities (marginal win probability)')
    L.push('')
    L.push(`Baseline: **${pct(prescription.baselineWinProb)}** average win probability across ${prescription.matches} matches.`)
    L.push('')
    L.push(row(['Priority', 'Improvement', 'Δ win prob', 'Hours', 'per 10h', 'Assumption']))
    L.push(row(['---', '---', '---', '---', '---', '---']))
    prescription.dims.forEach((d, i) => {
      L.push(row([i + 1, `${d.label} (+${d.gainPoints} ${d.unit})`, `+${(d.deltaP * 100).toFixed(1)}pp`, d.hours, `${d.roiPer10h}pp`, d.note]))
    })
    L.push('')
    if (prescription.caveat) L.push(`_${prescription.caveat}_`, '')
  }

  if (prescription?.gaps?.length) {
    L.push('## Gap to the top decile')
    L.push('')
    L.push(row(['Metric', 'You', 'Top decile', 'Gap', 'Percentile']))
    L.push(row(['---', '---', '---', '---', '---']))
    for (const g of prescription.gaps.filter((x) => x.gap != null)) {
      L.push(row([g.label, g.value, g.topDecile, g.gap, pct(g.percentile)]))
    }
    L.push('')
  }

  L.push('## Match log')
  L.push('')
  L.push(row(['Round', 'Match', 'Alliance', 'Score', 'Opponent', 'P(win)']))
  L.push(row(['---', '---', '---', '---', '---', '---']))
  for (const m of teamView.matches) {
    L.push(
      row([
        m.roundLabel,
        m.matchnum,
        m.own.join(' + '),
        m.ownScore == null ? '—' : `${m.ownScore}–${m.oppScore}`,
        m.opp.join(' + '),
        pct(m.pWin)
      ])
    )
  }
  L.push('')
  L.push('---')
  L.push('_Generated by Override Lab._')
  return L.join('\n')
}
